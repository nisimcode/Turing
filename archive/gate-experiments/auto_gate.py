def load_api_key() -> str:
    for var in ("ANTHROPIC_API_KEY", "CLAUDE_API_KEY"):
        if os.environ.get(var):
            return os.environ[var]
    for env_path in (HERE / ".env", HERE.parent / ".env"):
        if env_path.exists():
            for line in env_path.read_text(encoding="utf-8").splitlines():
                line = line.strip()
                if line.startswith(("CLAUDE_API_KEY=", "ANTHROPIC_API_KEY=")):
                    return line.split("=", 1)[1].strip().strip('"').strip("'")
    sys.exit("No API key found (set CLAUDE_API_KEY in E:\\Turing\\.env).")


client = anthropic.Anthropic(api_key=load_api_key())
_cost = 0.0


def gen_oracle(model, task):
    """Ask `model` for the test battery. Returns list of {args, expected}."""
    global _cost
    prompt = ORACLE_PROMPT.format(request=task["request"],
                                  signature=task["signature"],
                                  notes=task["notes"])
    resp = client.messages.create(
        model=model, max_tokens=2048,
        messages=[{"role": "user", "content": prompt}],
    )
    ip, op = PRICING[model]
    _cost += resp.usage.input_tokens / 1e6 * ip + resp.usage.output_tokens / 1e6 * op
    text = "".join(b.text for b in resp.content if b.type == "text")
    m = re.search(r"```(?:json)?\s*\n(.*?)```", text, re.DOTALL)
    raw = m.group(1) if m else text
    try:
        data = json.loads(raw)
    except json.JSONDecodeError:
        return []
    tests = data.get("tests", [])
    return [t for t in tests if isinstance(t, dict) and "args" in t and "expected" in t]


def build_html(impl_code):
    """Mechanical scaffold: a minimal-but-real UI + a generic window.__fn hook.

    (Must clear the runtime floor -- e.g. has_dom >= 5 elements -- so a floor
    failure can't be mistaken for an oracle disagreement.)
    """
    return (
        "<!doctype html><html><head><meta charset='utf-8'><title>tool</title></head>"
        "<body>"
        "<header><h1>Tool</h1></header>"
        "<main>"
        "<section><label for='in'>Input</label>"
        "<input id='in' placeholder='value'></section>"
        "<section><button id='b'>Run</button></section>"
        "<section><div id='out'>ready</div></section>"
        "</main>"
        "<footer><small>demo</small></footer>"
        "<script>\n" + impl_code + "\n"
        "window.__fn = function() { return __IMPL__.apply(null, arguments); };\n"
        "document.getElementById('b').onclick = () => "
        "{ document.getElementById('out').textContent = 'ok'; };\n"
        "</script></body></html>"
    )


def make_html(impl_code, fn_name):
    return build_html(impl_code).replace("__IMPL__", fn_name)


def make_functional(battery):
    """Build a gate `functional` hook from an auto-generated battery."""
    def checks(page):
        out = []
        has = page.evaluate("typeof window.__fn === 'function'")
        out.append({"name": "contract", "ok": bool(has), "detail": "window.__fn"})
        if not has or not battery:
            if not battery:
                out.append({"name": "oracle_present", "ok": False,
                            "detail": "empty/unparseable battery"})
            return out
        mism = []
        for case in battery:
            try:
                got = page.evaluate("(a) => window.__fn.apply(null, a)", case["args"])
            except Exception as e:
                mism.append(f"{case['args']}: raised {str(e)[:40]}")
                continue
            if isinstance(got, list):
                got = list(got)
            if got != case["expected"]:
                mism.append(f"{case['args']}: got {got!r}, oracle said "
                            f"{case['expected']!r}")
        ok = not mism
        detail = ("all cases agree" if ok else
                  mism[0] + (f"  (+{len(mism)-1} more)" if len(mism) > 1 else ""))
        out.append({"name": "auto_battery", "ok": ok, "detail": detail,
                    "n_mismatch": len(mism)})
        return out
    return checks


def run_impl(impl_code, fn_name, battery):
    with tempfile.NamedTemporaryFile("w", suffix=".html", delete=False,
                                     encoding="utf-8") as f:
        path = f.name
        f.write(make_html(impl_code, fn_name))
    try:
        v = gate_html(path, functional=make_functional(battery))
        bat = next((c for c in v["checks"] if c["name"] == "auto_battery"), None)
        return v["passed"], (bat or {}).get("n_mismatch", -1), (bat or {}).get("detail", "")
    finally:
        try:
            os.remove(path)
        except OSError:
            pass


def main():
    print("Auto-generated gates vs hand-verified implementations\n")
    false_accepts = 0
    oracle_errors = 0
    rows = []

    for task in TASKS:
        fn_name = task["signature"].split("(")[0].replace("function", "").strip()
        for gname, gmodel in GENERATORS.items():
            battery = gen_oracle(gmodel, task)
            n = len(battery)
            cor_pass, cor_mis, cor_detail = run_impl(task["correct"], fn_name, battery)
            bug_pass, bug_mis, _ = run_impl(task["buggy"], fn_name, battery)

            if not cor_pass:
                oracle_errors += 1
            if bug_pass:
                false_accepts += 1

            rows.append((task["id"], gname, n, cor_pass, cor_mis, bug_pass, cor_detail))
            print(f"[{task['id']:8}] oracle by {gname:6} "
                  f"cases={n:<3} "
                  f"correct-impl={'PASS' if cor_pass else f'FAIL({cor_mis})':9} "
                  f"buggy-impl={'PASS <-- FALSE ACCEPT' if bug_pass else 'FAIL (caught)'}")
            if not cor_pass and cor_detail:
                print(f"             oracle disagreed with correct code: {cor_detail}")

    total = len(rows)
    print(f"\n=== summary over {total} auto-generated gates ===")
    print(f"  FALSE ACCEPTS (buggy code passed):     {false_accepts}/{total}"
          + ("   <-- FATAL CLASS" if false_accepts else "   (none)"))
    print(f"  wrong oracles (correct code rejected): {oracle_errors}/{total}")
    for gname in GENERATORS:
        sub = [r for r in rows if r[1] == gname]
        fa = sum(1 for r in sub if r[5])
        oe = sum(1 for r in sub if not r[3])
        print(f"    {gname:6}: false-accepts {fa}/{len(sub)}, wrong oracles {oe}/{len(sub)}")
    print(f"  oracle generation cost: ${_cost:.4f}")

    print("\n=== read ===")
    if false_accepts == 0 and oracle_errors == 0:
        print("  Auto-generated gates were sound on this sample: they passed correct")
        print("  code and caught every injected bug. The recipe may scale past a")
        print("  hand-built template library -- worth a larger, harder trial.")
    elif false_accepts:
        print("  A machine-generated oracle approved broken code. This is the fatal")
        print("  error class, now produced by the system itself -- auto-generated")
        print("  gates cannot be trusted unverified.")
    else:
        print("  No false accepts, but some oracles rejected correct code (wrong")
        print("  expected values) -> margin cost, and a sign oracle quality is shaky.")


if __name__ == "__main__":
    main()
