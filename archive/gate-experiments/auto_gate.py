"""ARCHIVED EXPERIMENT: can the system generate its own gate?

Every vertical so far needed a human-written scaffold + spec + ORACLE. That makes
the proven product a verified *template library*, not a general builder. The
scaling question is whether the gate artifacts can be produced automatically for
a request we never anticipated -- and the risky artifact is the ORACLE (the test
battery with expected values), because a wrong oracle silently approves wrong
code (the fatal false-accept class, now machine-generated).

Experiment: pin the mechanical part (function slot + hook) and auto-generate ONLY
the battery. Then run that auto-gate against hand-written implementations whose
correctness WE control:

  * correct impl  -> auto-gate should PASS.  If it fails, the oracle is wrong
                     (false-reject source; count the disagreeing cases).
  * buggy impl    -> auto-gate should FAIL.  If it passes, that is a machine-made
                     FALSE ACCEPT -- the fatal error class.

Oracles are generated by BOTH the cheap and strong model, to see whether oracle
generation is where paying for the stronger model finally pays off.

    uv run --with anthropic --with playwright --with pillow python auto_gate.py
"""

import json
import os
import re
import sys
import tempfile
from pathlib import Path

import anthropic

from browser_gate import gate_html

HERE = Path(__file__).resolve().parent
GENERATORS = {"haiku": "claude-haiku-4-5", "opus": "claude-opus-4-8"}
PRICING = {"claude-haiku-4-5": (1.0, 5.0), "claude-opus-4-8": (5.0, 25.0)}

ORACLE_PROMPT = """A developer is building this tool:

  {request}

The implementation must be a JavaScript function with EXACTLY this signature:

  {signature}

{notes}

Your job is to produce the TEST ORACLE that will decide whether an
implementation is correct. Output JSON only, in a single ```json code block:

{{"tests": [{{"args": [...], "expected": ...}}, ...]}}

Rules:
- `args` is the argument list passed to the function.
- `expected` is the exact correct return value (JSON: number, string, boolean,
  or array).
- Provide 8-14 cases and MAKE THEM COUNT: include the tricky edge cases that a
  subtly-wrong implementation would get wrong.
- Every expected value must be correct. A wrong expected value is worse than a
  missing test, because it makes the gate reject correct code or accept broken
  code."""

