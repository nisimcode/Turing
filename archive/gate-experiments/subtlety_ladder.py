"""ARCHIVED EXPERIMENT: fault-subtlety ladder for auto-gates.

The safety metric that decides everything is the FALSE-ACCEPT rate (broken code
passing). Earlier auto-gate evidence used clear-cut injected bugs, which is the
easy case. Here each task carries a LADDER of implementations of increasing
subtlety, all hand-verified by us:

  L0 correct          -- must PASS (a fail = false reject)
  L1 obvious          -- trivially broken (constant / no-op output)
  L2 systematic       -- whole-rule error (affects most inputs)
  L3 class-conditional-- fails only for a CLASS of inputs (multi-digit, even
                         length, a numeric range)
  L4 single-point     -- fails for exactly ONE input value, but a CANONICAL edge
                         case (empty / singleton / max) that a good test designer
                         probes by habit
  L5 arbitrary-point  -- fails for one ARBITRARY input nobody would think to
                         probe (a magic number, a rare substring). Tests the true
                         coverage limit of a finite battery.

Oracles are auto-generated by the strong tier (D23: strong tier is the oracle
authority). We measure false-accepts per subtlety level -- i.e. how deep
auto-generated test coverage actually goes.

    uv run --with anthropic --with playwright --with pillow python subtlety_ladder.py
"""

