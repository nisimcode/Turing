def load_api_key() -> str:
    for var in ("ANTHROPIC_API_KEY", "CLAUDE_API_KEY"):
        if os.environ.get(var):
            return os.environ[var]
    for env_path in (HERE / ".env", HERE.parent / ".env"):
        if env_path.exists():
            for line in env_path.read_text(encoding="utf-8").splitlines():
                line = line.strip()
                if line.startswith(("CLAUDE_API_KEY=", "ANTHROPIC_API_KEY=")):
                    return line.split("=", 1)[1].strip().strip('"').strip("'")
    sys.exit("No API key found (set CLAUDE_API_KEY in E:\\Turing\\.env).")


client = anthropic.Anthropic(api_key=load_api_key())
_cost = 0.0


def gen_oracle(task):
    global _cost
    prompt = ORACLE_PROMPT.format(signature=task["signature"], desc=task["desc"])
    resp = client.messages.create(model=ORACLE_MODEL, max_tokens=2048,
                                  messages=[{"role": "user", "content": prompt}])
    ip, op = PRICING[ORACLE_MODEL]
    _cost += resp.usage.input_tokens / 1e6 * ip + resp.usage.output_tokens / 1e6 * op
    text = "".join(b.text for b in resp.content if b.type == "text")
    m = re.search(r"```(?:json)?\s*\n(.*?)```", text, re.DOTALL)
    try:
        return json.loads(m.group(1) if m else text).get("tests", [])
    except (json.JSONDecodeError, AttributeError):
        return []


def make_functional(battery):
    def checks(page):
        out = [{"name": "contract",
                "ok": bool(page.evaluate("typeof window.__fn === 'function'")),
                "detail": "window.__fn"}]
        if not out[0]["ok"] or not battery:
            return out
        mism = 0
        first = ""
        for case in battery:
            try:
                got = page.evaluate("(a) => window.__fn.apply(null, a)", case["args"])
            except Exception:
                mism += 1
                continue
            if isinstance(got, list):
                got = list(got)
            if got != case["expected"]:
                mism += 1
                if not first:
                    first = f"{case['args']} -> {got!r} (want {case['expected']!r})"
        out.append({"name": "battery", "ok": mism == 0,
                    "detail": first or "all agree"})
        return out
    return checks


def run(impl, fn, battery):
    with tempfile.NamedTemporaryFile("w", suffix=".html", delete=False,
                                     encoding="utf-8") as f:
        path = f.name
        f.write(make_html(impl, fn))
    try:
        return gate_html(path, functional=make_functional(battery))["passed"]
    finally:
        try:
            os.remove(path)
        except OSError:
            pass


def main():
    levels = ["L0_correct", "L1_obvious", "L2_systematic", "L3_class", "L4_point",
              "L5_arbitrary"]
    caught = Counter()
    total = Counter()
    false_rejects = 0
    grid = defaultdict(dict)

    for task in TASKS:
        battery = gen_oracle(task)
        inputs = [c.get("args") for c in battery]
        print(f"\n=== {task['id']}: oracle has {len(battery)} cases ===")
        print(f"    inputs: {json.dumps(inputs)[:150]}")
        for lvl in levels:
            passed = run(task["impls"][lvl], task["fn"], battery)
            grid[task["id"]][lvl] = passed
            if lvl == "L0_correct":
                if not passed:
                    false_rejects += 1
                print(f"    {lvl:15} gate={'PASS' if passed else 'FAIL'}"
                      + ("" if passed else "   <-- FALSE REJECT"))
            else:
                total[lvl] += 1
                if not passed:
                    caught[lvl] += 1
                print(f"    {lvl:15} gate={'PASS' if passed else 'FAIL'}"
                      + ("   <-- FALSE ACCEPT" if passed else "   (caught)"))

    print("\n=== catch rate by bug subtlety ===")
    for lvl in levels[1:]:
        c, t = caught[lvl], total[lvl]
        fa = t - c
        print(f"  {lvl:15} caught {c}/{t}   false-accepts {fa}")
    tot_fa = sum(total[l] - caught[l] for l in levels[1:])
    tot_bugs = sum(total.values())
    print(f"\n  overall false-accept rate: {tot_fa}/{tot_bugs}")
    print(f"  false rejects (correct code failed): {false_rejects}/{len(TASKS)}")
    print(f"  oracle generation cost: ${_cost:.4f}")

    print("\n=== read ===")
    canonical_fa = sum(total[l] - caught[l]
                       for l in ("L1_obvious", "L2_systematic", "L3_class", "L4_point"))
    arb_fa = total["L5_arbitrary"] - caught["L5_arbitrary"]
    if tot_fa == 0:
        print("  Auto-generated oracles caught bugs at EVERY level, including")
        print("  arbitrary-point bugs. Coverage is deeper than a finite battery")
        print("  should manage -- worth re-checking the L5 impls actually differ.")
    elif canonical_fa == 0 and arb_fa:
        print("  Clean split: every bug on a CANONICAL input (boundary, empty,")
        print("  singleton, max) was caught; bugs on ARBITRARY inputs were missed.")
        print("  Auto-oracles probe where real bugs actually cluster, so they cover")
        print("  the realistic bug distribution -- but a finite battery is blind to")
        print("  arbitrarily-placed faults. Mitigation: property-based testing /")
        print("  fuzzing against a reference, not a fixed case list.")
    else:
        print("  False accepts appeared on canonical inputs too -- oracle coverage")
        print("  is weaker than the design assumes; auto-gates unsafe alone.")


if __name__ == "__main__":
    main()
